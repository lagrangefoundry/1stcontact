/**
 * The host's own record of what a delegation changed ([[REQ-340]], DOC-60 §1).
 *
 * WHY IT EXISTS. Everything else on a delegation result is the worker's word:
 * the `delegate` operation declares `provenance: "untrusted"`, so a worker that
 * reports nothing leaves nothing behind and a worker that reports wrongly is
 * not contradicted. Two of the seven delegations that had ever run came back
 * `outcome: silent` with real element writes committed on the site, and the
 * only recovery was to re-inspect the site at the consultant's rate — which is
 * the cost delegation exists to remove.
 *
 * SO THE HOST LOOKS FOR ITSELF. A capture of the draft is taken before the
 * worker is briefed and another after its work ends, and the difference between
 * them is derived here. No part of it comes from anything the worker says.
 *
 * STATE, NOT A LOG OF WRITES. The change journal is beside this and is
 * deliberately not its source, for the two reasons DOC-60 gives. An element
 * address is regenerated by every write, so a path-keyed per-write record can
 * misalign against a tree that has moved under it; and a journal record holds a
 * TEXT rendering of before and after, which was byte-identical on 276 of the
 * 337 `l1.set` records on the real log — because padding, colour, font size and
 * layout are most of what a worker changes and none of them change an element's
 * words. Comparing two states has neither failure: an address is read off the
 * tree it belongs to, and a difference is a difference whatever it is in.
 *
 * IT SPEAKS FOR A WINDOW, AND SETS APART WHAT THE JOURNAL PLACES ELSEWHERE
 * ([[BUG-225]]). Anything that writes to the draft between the two captures
 * appears in the comparison, whoever wrote it. The delegating session is blocked
 * awaiting its worker, so the other writer is the client in the page editor —
 * and an account that counted the client's own edit as the builder's failed the
 * builder's checks for it. The journal records who made each write, so the
 * difference a client write explains is moved to `others` with its actor. The
 * journal only ever narrows the builder's share: a difference it cannot place
 * stays with the builder. See {@link setApart}.
 *
 * WHAT IT COSTS. Both captures and the comparison are host-side and add no
 * tokens; only the difference list enters the conversation, and it is a list of
 * what CHANGED rather than of what is there. One element write measured 287
 * bytes against a 2,582-byte element. {@link DIFFERENCE_BUDGET} bounds the
 * pathological case out loud rather than quietly.
 *
 * A WHOLE THING IS NAMED, NOT COPIED ([[REQ-361]]). An element, a component or a
 * page that arrived, left or was swapped for another kind is reported as WHERE it
 * is, WHAT happened to it and HOW BIG it is — never as the tree itself. That was
 * where the record's weight was: a worker that built a page or restructured a box
 * came back with the whole subtree as `after`, four results of 53–70 KB in one
 * session, every byte of it re-read on every later request. The caller can read
 * the page when it needs the tree; a field that changed still carries both values.
 */

